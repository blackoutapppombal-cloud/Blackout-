for select to anon, authenticated
using (active and exists (select 1 from public.products p where p.id=product_id and p.active));
drop policy if exists "Admins manage product variants" on public.product_variants;
create policy "Admins manage product variants" on public.product_variants
for all to authenticated using (public.is_admin()) with check (public.is_admin());
grant select on public.product_variants to anon, authenticated;
grant insert, update, delete on public.product_variants to authenticated;
grant usage, select on sequence public.product_variants_id_seq to authenticated;

create or replace function public.sync_variant_product_totals(p_product_id bigint)
returns void language plpgsql security definer set search_path=public,pg_temp as $$
begin
  if exists(select 1 from public.product_variants where product_id=p_product_id) then
    update public.products set
      price=coalesce((select min(price) from public.product_variants where product_id=p_product_id and active),price),
      old_price=greatest(old_price,coalesce((select min(price) from public.product_variants where product_id=p_product_id and active),price)),
      stock=coalesce((select sum(stock) from public.product_variants where product_id=p_product_id and active),0),
      updated_at=now()
    where id=p_product_id;
  end if;
end;
$$;

create or replace function public.product_variants_after_change()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
begin
  perform public.sync_variant_product_totals(coalesce(new.product_id,old.product_id));
  if tg_op='UPDATE' and new.product_id is distinct from old.product_id then
    perform public.sync_variant_product_totals(old.product_id);
  end if;
  return coalesce(new,old);
end;
$$;
