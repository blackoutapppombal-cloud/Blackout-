begin;

alter table public.orders
  add column if not exists payment_method text,
  add column if not exists delivery_method text,
  add column if not exists admin_notes text,
  add column if not exists updated_at timestamptz not null default now();

create table if not exists public.services (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text not null default '',
  icon text not null default '⚙',
  price numeric(12,2) not null default 0 check (price >= 0),
  duration_label text not null default '',
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.service_orders (
  id bigint generated by default as identity primary key,
  service_id bigint references public.services(id) on delete set null,
  customer_name text not null,
  customer_phone text,
  customer_email text,
  device text not null,
  issue text not null default '',
  technical_notes text,
  estimate numeric(12,2) not null default 0 check (estimate >= 0),
  final_price numeric(12,2) check (final_price is null or final_price >= 0),
  status text not null default 'recebido' check (status in ('recebido','diagnostico','aguardando_aprovacao','em_reparo','pronto','entregue','cancelado')),
  due_date date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.banners (
  id bigint generated by default as identity primary key,
  eyebrow text not null default '',
  title text not null,
  subtitle text not null default '',
  image_url text,
  link_label text not null default 'Ver oferta',
  link_url text not null default '#offers',
  active boolean not null default true,
  sort_order integer not null default 0,
  starts_at timestamptz,
  ends_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint banners_schedule_valid check (ends_at is null or starts_at is null or ends_at > starts_at)
);

create table if not exists public.store_settings (
  id integer primary key default 1 check (id = 1),
  store_name text not null default 'BLACKOUT Infor Games',
  support_phone text not null default '',
  whatsapp text not null default '',
  support_email text not null default '',
  address text not null default '',
  business_hours text not null default '',
  instagram text not null default '',
  delivery_fee numeric(12,2) not null default 0 check (delivery_fee >= 0),
  free_shipping_min numeric(12,2) not null default 0 check (free_shipping_min >= 0),
  maintenance_mode boolean not null default false,
  updated_at timestamptz not null default now()
);

insert into public.services (name, description, icon, price, duration_label, sort_order)
