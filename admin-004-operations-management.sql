create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists orders_set_updated_at on public.orders;
create trigger orders_set_updated_at before update on public.orders for each row execute function public.set_updated_at();
drop trigger if exists services_set_updated_at on public.services;
create trigger services_set_updated_at before update on public.services for each row execute function public.set_updated_at();
drop trigger if exists service_orders_set_updated_at on public.service_orders;
create trigger service_orders_set_updated_at before update on public.service_orders for each row execute function public.set_updated_at();
drop trigger if exists banners_set_updated_at on public.banners;
create trigger banners_set_updated_at before update on public.banners for each row execute function public.set_updated_at();
drop trigger if exists store_settings_set_updated_at on public.store_settings;
create trigger store_settings_set_updated_at before update on public.store_settings for each row execute function public.set_updated_at();

alter table public.services enable row level security;
alter table public.service_orders enable row level security;
alter table public.banners enable row level security;
alter table public.store_settings enable row level security;

drop policy if exists "Public can read active services" on public.services;
create policy "Public can read active services" on public.services for select to anon, authenticated using (active = true or public.is_admin());
drop policy if exists "Admins manage services" on public.services;
create policy "Admins manage services" on public.services for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Admins manage service orders" on public.service_orders;
create policy "Admins manage service orders" on public.service_orders for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Public can read active banners" on public.banners;
create policy "Public can read active banners" on public.banners for select to anon, authenticated
using (active = true and (starts_at is null or starts_at <= now()) and (ends_at is null or ends_at >= now()) or public.is_admin());
drop policy if exists "Admins manage banners" on public.banners;
create policy "Admins manage banners" on public.banners for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Public can read store settings" on public.store_settings;
create policy "Public can read store settings" on public.store_settings for select to anon, authenticated using (id = 1);
drop policy if exists "Admins manage store settings" on public.store_settings;
create policy "Admins manage store settings" on public.store_settings for all to authenticated using (public.is_admin()) with check (public.is_admin());

grant select, insert, update, delete on public.orders to authenticated;
grant usage, select on sequence public.orders_id_seq to authenticated;
grant select on public.services, public.banners, public.store_settings to anon, authenticated;
grant insert, update, delete on public.services, public.service_orders, public.banners, public.store_settings to authenticated;
grant select on public.service_orders to authenticated;
grant usage, select on sequence public.services_id_seq, public.service_orders_id_seq, public.banners_id_seq to authenticated;

commit;
