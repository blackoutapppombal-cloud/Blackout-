create or replace function public.checkout_calculate(
  p_items jsonb, p_coupon text, p_delivery_method text, p_lock boolean default false
) returns jsonb
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
  entry jsonb;
  item record;
  product_row public.products%rowtype;
  coupon_row public.checkout_coupons%rowtype;
  settings_row public.store_settings%rowtype;
  seen bigint[] := '{}';
  snapshot jsonb := '[]'::jsonb;
  subtotal numeric(12,2) := 0;
  eligible numeric(12,2) := 0;
  discount_total numeric(12,2) := 0;
  shipping_total numeric(12,2) := 0;
  quantity integer;
  normalized_coupon text := nullif(upper(btrim(coalesce(p_coupon,''))), '');
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 50 then
    raise exception 'Carrinho inválido.';
  end if;
  if p_delivery_method not in ('entrega','retirada') then
    raise exception 'Escolha uma forma de entrega.';
  end if;
  for item in
    select (value->>'product_id')::bigint as product_id, value
    from jsonb_array_elements(p_items) as value
    order by (value->>'product_id')::bigint
  loop
    entry := item.value;
    if item.product_id is null or item.product_id = any(seen)
       or (entry->>'quantity') !~ '^[1-9][0-9]{0,3}$' then
      raise exception 'Item ou quantidade inválida.';
    end if;
    seen := array_append(seen,item.product_id);
    quantity := (entry->>'quantity')::integer;
    if p_lock then
      select * into product_row from public.products where id = item.product_id for update;
    else
      select * into product_row from public.products where id = item.product_id;
    end if;
    if not found or not product_row.active then
      raise exception 'Produto indisponível: %', item.product_id;
    end if;
    if product_row.stock < quantity then
      raise exception 'Estoque insuficiente: % (disponível: %)', product_row.name, product_row.stock;
    end if;
    subtotal := subtotal + product_row.price * quantity;
    snapshot := snapshot || jsonb_build_array(jsonb_build_object(
      'product_id', product_row.id, 'name', product_row.name, 'sku', coalesce(product_row.sku,'BIG-' || product_row.id),
      'image_url', product_row.image_url, 'quantity', quantity,
      'unit_price', product_row.price, 'subtotal', product_row.price * quantity
    ));
  end loop;
  if normalized_coupon is not null then
    if p_lock then
      select * into coupon_row from public.checkout_coupons where code = normalized_coupon for update;
    else
      select * into coupon_row from public.checkout_coupons where code = normalized_coupon;
    end if;
    if not found or not coupon_row.active then raise exception 'Cupom inválido.'; end if;
    if coupon_row.starts_at is not null and now() < coupon_row.starts_at then raise exception 'Cupom ainda não está válido.'; end if;
    if coupon_row.ends_at is not null and now() > coupon_row.ends_at then raise exception 'Cupom expirado.'; end if;
    if coupon_row.max_uses is not null and coupon_row.used_count >= coupon_row.max_uses then raise exception 'Cupom esgotado.'; end if;
    if subtotal < coupon_row.minimum_subtotal then raise exception 'Valor mínimo do cupom não atingido.'; end if;
    if coupon_row.max_uses_per_customer is not null then
      if auth.uid() is null then raise exception 'Entre na sua conta para usar este cupom.'; end if;
      if (select count(*) from public.orders
          where customer_id = auth.uid() and coupon_code = normalized_coupon
          and payment_status not in ('failed','cancelled')) >= coupon_row.max_uses_per_customer then
        raise exception 'Limite do cupom por cliente atingido.';
      end if;
    end if;
    select coalesce(sum((value->>'subtotal')::numeric),0) into eligible
    from jsonb_array_elements(snapshot) as value
    join public.products p on p.id = (value->>'product_id')::bigint
    where (coupon_row.allowed_product_ids is null or p.id = any(coupon_row.allowed_product_ids))
      and (coupon_row.allowed_categories is null or p.category = any(coupon_row.allowed_categories));
    if eligible <= 0 then raise exception 'Cupom não se aplica aos produtos do carrinho.'; end if;
    discount_total := least(eligible,
      case when coupon_row.discount_type = 'percent'
        then round(eligible * coupon_row.discount_value / 100, 2)
        else coupon_row.discount_value end);
  end if;
  if p_delivery_method = 'entrega' then
    select * into settings_row from public.store_settings where id = 1;
    if not found or not settings_row.delivery_checkout_enabled then
      raise exception 'Entrega ainda não está disponível no checkout. Escolha retirada na loja.';
    end if;
    shipping_total := case
      when settings_row.free_shipping_min > 0 and subtotal - discount_total >= settings_row.free_shipping_min then 0
      else settings_row.delivery_fee end;
  end if;
  return jsonb_build_object('items',snapshot,'subtotal',subtotal,'discount_total',discount_total,
    'shipping_total',shipping_total,'total',subtotal-discount_total+shipping_total,
    'coupon_code',normalized_coupon,'delivery_method',p_delivery_method);
end;
$$;
revoke all on function public.checkout_calculate(jsonb,text,text,boolean) from public, anon, authenticated;

