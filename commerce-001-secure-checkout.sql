create or replace function public.checkout_place_order(
  p_items jsonb, p_coupon text, p_delivery_method text, p_payment_method text,
  p_customer jsonb, p_address jsonb, p_idempotency_key uuid, p_expected_total numeric
) returns jsonb
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
  quote jsonb;
  existing public.orders%rowtype;
  placed public.orders%rowtype;
  item jsonb;
  method_row public.checkout_payment_methods%rowtype;
  safe_address jsonb;
begin
  if p_idempotency_key is null then raise exception 'Identificador da tentativa obrigatório.'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_idempotency_key::text,0));
  select * into existing from public.orders where idempotency_key = p_idempotency_key;
  if found then
    return jsonb_build_object('order_number',existing.order_number,'tracking_token',existing.tracking_token,
      'items',existing.items,'subtotal',existing.subtotal,'discount_total',existing.discount_total,
      'shipping_total',existing.shipping_total,'total',existing.total,'status',existing.status,
      'payment_status',existing.payment_status,'delivery_method',existing.delivery_method,
      'payment_method',existing.payment_method);
  end if;
  if length(btrim(coalesce(p_customer->>'name',''))) < 2
     or coalesce(p_customer->>'email','') !~ '^[^@[:space:]]+@[^@[:space:]]+[.][^@[:space:]]+$'
     or length(regexp_replace(coalesce(p_customer->>'phone',''),'[^0-9]','','g')) not between 10 and 11 then
    raise exception 'Dados do cliente inválidos.';
  end if;
  select * into method_row from public.checkout_payment_methods where code = p_payment_method and active;
  if not found then raise exception 'Forma de pagamento indisponível.'; end if;
  if p_delivery_method = 'entrega' then
    if length(regexp_replace(coalesce(p_address->>'cep',''),'[^0-9]','','g')) <> 8
       or length(btrim(coalesce(p_address->>'street',''))) < 2
       or length(btrim(coalesce(p_address->>'number',''))) < 1
       or length(btrim(coalesce(p_address->>'neighborhood',''))) < 2
       or length(btrim(coalesce(p_address->>'city',''))) < 2
       or coalesce(p_address->>'state','') !~ '^[A-Z]{2}$' then
      raise exception 'Endereço de entrega incompleto.';
    end if;
    safe_address := jsonb_build_object(
      'cep',p_address->>'cep','street',p_address->>'street','number',p_address->>'number',
      'complement',p_address->>'complement','neighborhood',p_address->>'neighborhood',
      'city',p_address->>'city','state',p_address->>'state','reference',p_address->>'reference');
  else
    safe_address := null;
  end if;
  quote := public.checkout_calculate(p_items,p_coupon,p_delivery_method,true);
  if p_expected_total is null or p_expected_total <> (quote->>'total')::numeric then
    raise exception 'Valores atualizados. Revise o pedido antes de confirmar.';
  end if;
  insert into public.orders(customer_id,customer_name,customer_email,customer_phone,items,
    subtotal,discount_total,shipping_total,total,coupon_code,delivery_method,delivery_address,
    payment_method,payment_status,status,idempotency_key,stock_reserved)
  values (auth.uid(),btrim(p_customer->>'name'),btrim(p_customer->>'email'),btrim(p_customer->>'phone'),
    quote->'items',(quote->>'subtotal')::numeric,(quote->>'discount_total')::numeric,
    (quote->>'shipping_total')::numeric,(quote->>'total')::numeric,
    quote->>'coupon_code',p_delivery_method,safe_address,p_payment_method,'pending','recebido',p_idempotency_key,true)
  returning * into placed;
  update public.orders set order_number = 'BIG-' || lpad(placed.id::text,8,'0')
    where id = placed.id returning * into placed;
  for item in select value from jsonb_array_elements(quote->'items') as value loop
    update public.products set stock = stock - (item->>'quantity')::integer
      where id = (item->>'product_id')::bigint and stock >= (item->>'quantity')::integer;
    if not found then raise exception 'Estoque insuficiente: %', item->>'name'; end if;
  end loop;
  if (quote->>'coupon_code') is not null then
    update public.checkout_coupons set used_count = used_count + 1 where code = quote->>'coupon_code';
  end if;
  return jsonb_build_object('order_number',placed.order_number,'tracking_token',placed.tracking_token,
    'items',placed.items,'subtotal',placed.subtotal,'discount_total',placed.discount_total,
    'shipping_total',placed.shipping_total,'total',placed.total,'status',placed.status,
    'payment_status',placed.payment_status,'delivery_method',placed.delivery_method,
    'payment_method',placed.payment_method);
end;
$$;
revoke all on function public.checkout_place_order(jsonb,text,text,text,jsonb,jsonb,uuid,numeric) from public;
grant execute on function public.checkout_place_order(jsonb,text,text,text,jsonb,jsonb,uuid,numeric) to anon, authenticated;

