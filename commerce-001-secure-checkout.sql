-- A pending order reserves stock. Releasing a cancelled/failed order happens once.
create or replace function public.checkout_release_stock()
returns trigger language plpgsql security definer
set search_path = public, pg_temp
as $$
declare item jsonb;
begin
  if not old.stock_reserved then return new; end if;
  if new.status = 'pago' and old.status is distinct from 'pago' then
    new.payment_status := 'paid';
  end if;
  if new.status = 'cancelado' and new.payment_status = 'pending' then
    new.payment_status := 'cancelled';
  end if;
  if new.payment_status in ('failed','cancelled') then
    new.status := 'cancelado';
  end if;
  if old.stock_released then
    if new.payment_status = 'paid' or new.status in ('pago','em_preparacao','pronto','concluido') then
      raise exception 'Pedido cancelado não pode ser reativado sem nova reserva de estoque.';
    end if;
    new.stock_released := true;
    return new;
  end if;
  if new.status = 'cancelado' or new.payment_status in ('failed','cancelled') then
    for item in select value from jsonb_array_elements(new.items) as value loop
      update public.products set stock = stock + (item->>'quantity')::integer
        where id = (item->>'product_id')::bigint;
    end loop;
    if new.coupon_code is not null then
      update public.checkout_coupons set used_count = greatest(0,used_count-1)
        where code = new.coupon_code;
    end if;
    new.stock_released := true;
  end if;
  return new;
end;
$$;
drop trigger if exists checkout_release_stock_trigger on public.orders;
create trigger checkout_release_stock_trigger before update of status,payment_status on public.orders
for each row execute function public.checkout_release_stock();

